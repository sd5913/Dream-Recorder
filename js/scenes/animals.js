const rect=(x0,y0,x1,y1)=>[[x0,y0],[x1,y0],[x1,y1],[x0,y1]];
/* thin legs are one line of words; thick legs are filled columns */
function legs(xs,y0,y1,col,w){xs.forEach(x=>{if(w)hatch([rect(x-w/2,y0,x+w/2,y1)],Math.PI/2,col,{min:.05});else S([[x,y0],[x,y1]],col);});}
const tail=(a,b,c,d,col)=>S(bez(a,b,c,d,30),col,{keep:1});

